// Embeds tree-sitter's runtime and the bash grammar in a generated module, so
// the Claude hook ships as one text file.

const sources = {
  TREE_SITTER: "node_modules/web-tree-sitter/tree-sitter.wasm",
  BASH: "node_modules/tree-sitter-bash/tree-sitter-bash.wasm",
};
const lines = ["// Generated by scripts/embed-wasm.ts; do not edit."];
for (const [name, path] of Object.entries(sources)) {
  const bytes = await Bun.file(`${import.meta.dir}/../${path}`).bytes();
  lines.push(`export const ${name} = "${bytes.toBase64()}"`);
}
await Bun.write(`${import.meta.dir}/../src/wasm.generated.ts`, lines.join("\n") + "\n");
